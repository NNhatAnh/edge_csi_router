def rank_eta(values, labels):
    centered = values - values.mean(axis=0)
    between = sum(
        (centered[labels == k].sum(axis=0) ** 2 / sum(labels == k) for k in np.unique(labels))
    )
    return between / (np.sum(centered**2, axis=0) + 1e-12)


def permutations(labels, task):
    n = len(labels)
    classes = np.unique(labels)
    if task == "presence":
        empty = classes.tolist().index("EMPTY")
        k = sum(labels == "EMPTY")
        for subset in itertools.combinations(range(n), k):
            y = np.full(n, 1 - empty)
            y[list(subset)] = empty
            yield y
    elif task == "distance":
        assert (
            len(classes) == 3
        ), "Exact distance permutation yêu cầu 3 class; sửa protocol khi data có thêm/bớt class."
        counts = [sum(labels == c) for c in classes]
        for first in itertools.combinations(range(n), counts[0]):
            remaining = [i for i in range(n) if i not in first]
            for second in itertools.combinations(remaining, counts[1]):
                y = np.full(n, 2)
                y[list(first)] = 0
                y[list(second)] = 1
                yield y
    else:
        y = np.searchsorted(classes, labels)
        for _ in range(BEHAVIOR_PERMUTATIONS):
            yield RNG.permutation(y)


